// Writes firmware/sim/scenarios.json: labelled meter windows for choosing and testing the 0G decision model (0G-1).
// `expect` is the answer a careful operator would give. Borderline cases are included on purpose.
import fs from "node:fs";
import path from "node:path";

type Win = { valid_pulses: number; glitches: number; stuck_low: number; avg_watts: number; peak_watts: number; longest_gap_s: number; previous_avg_watts?: number };
const W = (name: string, expect: "run" | "inspect", why: string, o: Partial<Win>, credit = 2000) => ({
  name,
  expect,
  why,
  window: { window_s: 60, valid_pulses: 0, glitches: 0, stuck_low: 0, avg_watts: 0, peak_watts: 0, longest_gap_s: 0, ...o },
  context: { sanctioned_load_w: 5000, meter_max_w: 13800, credit_pulses_left: credit, hold: false },
});

const scenarios = [
  W("idle standby", "run", "standby load", { valid_pulses: 1, avg_watts: 60, peak_watts: 70, longest_gap_s: 30 }),
  W("normal household", "run", "typical", { valid_pulses: 19, avg_watts: 900, peak_watts: 1000, longest_gap_s: 3.5 }),
  W("normal evening", "run", "typical", { valid_pulses: 34, avg_watts: 1600, peak_watts: 1900, longest_gap_s: 2.4 }),
  W("heavy but sanctioned", "run", "geyser running, below 5 kW", { valid_pulses: 56, avg_watts: 3000, peak_watts: 3300, longest_gap_s: 1.2 }),
  W("busy but within limit", "run", "AC plus geyser, 4.6 kW", { valid_pulses: 86, avg_watts: 4600, peak_watts: 4800, longest_gap_s: 0.9 }),
  W("above sanctioned load", "inspect", "sustained 8 kW against a 5 kW sanction", { valid_pulses: 150, avg_watts: 8000, peak_watts: 8300, longest_gap_s: 0.5 }),
  W("far above sanctioned load", "inspect", "sustained 11 kW", { valid_pulses: 206, avg_watts: 11000, peak_watts: 11500, longest_gap_s: 0.4 }),
  W("sudden silence after load", "inspect", "previous window averaged 3 kW, now no pulses though the line is healthy", { longest_gap_s: 60, previous_avg_watts: 3000 }),
  W("one glitch only", "run", "a single short spike is common interference", { valid_pulses: 19, glitches: 1, avg_watts: 900, peak_watts: 1000, longest_gap_s: 3.5 }),
  W("repeated glitches", "inspect", "5 spikes in a minute on the pulse line", { valid_pulses: 19, glitches: 5, avg_watts: 900, peak_watts: 1000, longest_gap_s: 3.5 }),
  W("stuck low line", "inspect", "line held low: wiring fault or tampering", { valid_pulses: 3, stuck_low: 1, avg_watts: 600, peak_watts: 900, longest_gap_s: 35 }),
  W("irregular timing", "inspect", "spacing swings from 0.2 s to 20 s at the same average, not like a real load", { valid_pulses: 19, avg_watts: 900, peak_watts: 9000, longest_gap_s: 20 }),
  W("low credit, normal usage", "run", "low credit is the ledger's concern, not an anomaly", { valid_pulses: 19, avg_watts: 900, peak_watts: 1000, longest_gap_s: 3.5 }, 15),
  W("borderline just over sanction", "inspect", "5.4 kW against 5 kW, sustained", { valid_pulses: 101, avg_watts: 5400, peak_watts: 5600, longest_gap_s: 0.7 }),
  // Held-out: added after the first evaluation round, and not used when writing the policy text.
  W("moderate overload", "inspect", "6.5 kW sustained against a 5 kW sanction", { valid_pulses: 122, avg_watts: 6500, peak_watts: 6800, longest_gap_s: 0.6 }),
  W("load resumes after an outage", "run", "previous window had no load, now an ordinary 900 W", { valid_pulses: 19, avg_watts: 900, peak_watts: 1000, longest_gap_s: 3.5, previous_avg_watts: 0 }),
  W("two glitches", "run", "two short spikes in a minute is within normal interference", { valid_pulses: 28, glitches: 2, avg_watts: 1300, peak_watts: 1500, longest_gap_s: 2.4 }),
  W("brief peak within sanction", "run", "average 1.2 kW, one 4.8 kW burst, all under the sanction", { valid_pulses: 22, avg_watts: 1200, peak_watts: 4800, longest_gap_s: 3 }),
  W("glitchy and irregular", "inspect", "3 glitches and spacing that does not look like a real load", { valid_pulses: 15, glitches: 3, avg_watts: 700, peak_watts: 8000, longest_gap_s: 18 }),
];

const out = path.resolve(import.meta.dirname, "../../firmware/sim/scenarios.json");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  JSON.stringify({ description: "Labelled meter windows for the 0G decision model (0G-1). Generated by signer/tools/make-scenarios.ts.", pulses_per_kwh: 3200, scenarios }, null, 2) + "\n",
);
console.log(`${scenarios.length} scenarios: ${scenarios.filter((s) => s.expect === "run").length} run, ${scenarios.filter((s) => s.expect === "inspect").length} inspect`);
